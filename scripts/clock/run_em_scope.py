"""GoalScope over an emergently-misaligned (EM) LoRA model and its innocent base.

For one prompt, renders two GoalScope HTML files:

``<slug>__em__seed<seed>.html``
    The response is generated by the **EM model** (base + risky-financial-advice LoRA).
    Goal signals are read from the EM model's selected heads, but the *verbalizer* — the
    model that is actually steered and generates the tooltip text — is the **BASE** model.
    So the readout is "what does an unmodified Qwen say this goal state is about?", which
    keeps the verbalization itself free of the adapter's misalignment.

``<slug>__innocent__seed<seed>.html``
    Control: the base model both generates the response and verbalizes it.

Both models live in ONE set of weights — two 32B bf16 copies do not fit on 2x48 GB.  The
adapter is toggled with ``enable_adapter_layers()`` / ``disable_adapter_layers()``, which
route the forward pass through (or around) the LoRA branch **without touching any weight
tensor**, so the toggle is exact and endlessly repeatable.

Do NOT use ``merge_adapter()`` / ``unmerge_adapter()`` for this.  Those mutate
``base_layer.weight`` in place, and in bf16 (8-bit mantissa) ``(W + delta) - delta`` does
not return ``W``: the round-trip leaves an error on the order of ``W``'s own quantisation
step, which is far larger than activation noise.  A merge/unmerge cycle therefore leaves a
*perturbed* model behind, and any later "base" forward pass silently runs on it.

The one thing enable/disable does not fix is ``collect_head_steering_vecs``, which reads
``o_proj.weight`` directly to turn o_proj inputs into residual-stream writes.  ``o_proj``
is a LoRA target here, so with the adapter merely enabled that read returns the *base*
``W_o`` and the EM head-write would be half wrong.  ``em_o_proj_weights`` below rebuilds
the effective EM ``W_o`` from the adapter tensors and passes it in via
``src_w_o_override``.

Typical usage
─────────────
conda run -n goals python scripts/clock/run_em_scope.py

conda run -n goals python scripts/clock/run_em_scope.py \\
    --user-prompt "How do I make a quick buck?" \\
    --slug how_quick_buck \\
    --seeds 0-49 \\
    --save-json --output-dir notebooks/clock

The response under analysis is SAMPLED by default, so --seeds is what makes a run
reproducible.  It takes individual values and inclusive ranges (``0-49`` = 50 seeds); the
model is loaded ONCE and reused across the whole sweep, and each seed is re-applied per
condition so a seed's output does not depend on which other seeds ran.  Pass --greedy for
deterministic decoding instead (tagged ``__greedy`` in the filename).  Either way the
per-token GoalScope verbalizations are greedy and unaffected.

Sampling params (temperature/top_p/top_k/repetition_penalty) default to Qwen2.5-Instruct's
own generation_config values and are ALWAYS passed explicitly — nnsight's generate() does
not read that file, so omitting them disables truncation entirely rather than falling back
to it.  Do not raise --temperature or clear --top-k without checking the base-condition
output: untruncated sampling degenerates it while leaving the low-entropy EM model looking
fine, which makes the breakage easy to miss.

Only the EM side:
conda run -n goals python scripts/clock/run_em_scope.py --conditions em
"""

