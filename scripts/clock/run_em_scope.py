def run_condition(
    *,
    mt: ModelandTokenizer,
    lora_root,
    condition: str,
    args: argparse.Namespace,
    seed: Optional[int],
    goal_heads: list[tuple[int, int]],
    out_path: Path,
) -> dict:
    """Generate a response, GoalScope it, write the HTML; return a JSON-able record.

    ``condition="em"``: response + goal signal from the EM weights, verbalizer = base.
    ``condition="innocent"``: base weights throughout.
    """
    em = condition == "em"
    src_state = "em" if em else "base"

    test_prompt = build_chat_prompt(mt, args.system_prompt, args.user_prompt)

    # The response under analysis comes from the same weights the goal signal is read
    # from — scoping an EM response through base-model activations would make the source
    # signal describe a trajectory those weights never chose.
    with weights(lora_root, src_state):
        logger.info(
            f"[{condition}] src fingerprint ({src_state}) = "
            f"{weight_fingerprint(mt, src_state):.6f}"
        )
        tokenized = prepare_input(test_prompt, mt, padding_side="left")
        sample_kwargs = {}
        if not args.greedy:
            # ALWAYS passed explicitly, never left to fall back on the checkpoint's
            # generation_config: nnsight's generate() does not inherit it, so an omitted
            # top_k/top_p means NO truncation rather than Qwen's 20/0.8.  Sampling the
            # raw softmax over a 152k vocab derails the base model within a few hundred
            # tokens (observed: a response opening on the token "恝", which top_k=20
            # would have made impossible).  The fine-tuned EM model hides this — narrow
            # SFT lowers its output entropy enough to stay on-rails untruncated — so the
            # bug shows up only in the innocent condition.
            sample_kwargs = {
                "temperature": args.temperature,
                "top_p": args.top_p,
                "top_k": args.top_k,
                "repetition_penalty": args.repetition_penalty,
            }
            logger.info(f"[{condition}] sampling {sample_kwargs} seed={seed}")
            set_seed(seed)
        test_gen = generate_with_patch(
            mt,
            inputs=tokenized,
            n_gen_per_prompt=1,
            max_new_tokens=args.response_max_new_tokens,
            do_sample=not args.greedy,
            remove_prefix=True,
            **sample_kwargs,
        )[0]

    logger.info(f"[{condition}] response: {test_gen[:200]!r}")

    goalscope_prompt = build_chat_prompt(
        mt, args.system_prompt, args.goalscope_question
    )

    # W_o override: enable/disable never folds the adapter into o_proj.weight, so for the
    # EM source the head-write matrix has to be supplied explicitly.  Additive only.
    w_o_override = None
    if em and args.strategy != "replace":
        w_o_override = em_o_proj_weights(mt, sorted({l for l, _ in goal_heads}))
        logger.info(f"[{condition}] EM W_o override for {len(w_o_override)} layers")

    results = apply_goalscope(
        prompt=test_prompt + test_gen,
        mt=mt,
        src_mt=mt,  # one loaded model; the *weight state* differs, see src/dest contexts
        src_context=lambda: weights(lora_root, src_state),
        dest_context=lambda: weights(lora_root, "base"),  # verbalizer is ALWAYS base
        src_w_o_override=w_o_override,
        selected_heads=goal_heads,
        strategy=args.strategy,
        alpha=args.alpha,
        steer_layer_range=tuple(args.steer_layer_range),
        max_new_tokens=args.max_new_tokens,
        n_steer_tokens="all",
        batch_size=args.batch_size,
        title=f"GoalScope ({condition}, {decode_tag(args.greedy, seed)})",
        show=False,
        include_noncode=True,
        goalscope_prompt=goalscope_prompt,
        save_path=str(out_path),
    )
    return {
        "condition": condition,
        "decode": "greedy" if args.greedy else "sample",
        "seed": seed,
        "sampling": None if args.greedy else sample_kwargs,
        "system_prompt": args.system_prompt,
        "user_prompt": args.user_prompt,
        "goalscope_question": args.goalscope_question,
        "response": test_gen,
        "html": str(out_path),
        "results": results,
    }


