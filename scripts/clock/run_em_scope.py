def load_em_model(
    base: str, adapter: str, cache_dir: str
) -> tuple[ModelandTokenizer, object]:
    """Load base + un-merged LoRA; return ``(mt, lora_root)``.

    ``mt`` wraps ``peft_model.base_model.model`` — the original ``Qwen2ForCausalLM``
    instance, with LoRA-injected ``Linear``s swapped in place.  Wrapping the inner model
    rather than the ``PeftModel`` keeps every module path at ``model.layers.<i>.…``, which
    is what ``ModelandTokenizer``'s hard-coded ``layer_name_format`` and every baukit hook
    in this repo expect; a ``PeftModel`` wrapper would prefix them with ``base_model.model``
    and break all of them.

    ``lora_root`` is the ``LoraModel`` exposing ``enable_adapter_layers`` /
    ``disable_adapter_layers``.
    """
    from nnsight import LanguageModel
    from peft import PeftModel
    from transformers import AutoModelForCausalLM, AutoTokenizer

    logger.info(f"Loading base model {base}")
    hf = AutoModelForCausalLM.from_pretrained(
        base,
        dtype=torch.bfloat16,
        device_map="auto",
        attn_implementation="eager",
        cache_dir=cache_dir,
    )
    logger.info(f"Attaching adapter {adapter} (un-merged)")
    peft_model = PeftModel.from_pretrained(hf, adapter, cache_dir=cache_dir)
    peft_model.eval()
    # Park the model in the BASE state so the resting state is known rather than assumed.
    peft_model.base_model.disable_adapter_layers()

    inner = peft_model.base_model.model
    tok = AutoTokenizer.from_pretrained(adapter, cache_dir=cache_dir)
    mt = ModelandTokenizer(base_lm=LanguageModel(inner, tokenizer=tok))
    mt.config = mt._model.config
    mt.name = base.split("/")[-1]
    return mt, peft_model.base_model


def set_seed(seed: int) -> None:
    """Seed every RNG that ``generate_with_patch`` sampling can draw from.

    Called immediately before each condition's response generation rather than once at
    startup: the conditions run in sequence and consume RNG, so a single global seed would
    make the second condition's sample depend on whether the first one ran.  Re-seeding per
    condition keeps ``--conditions em innocent`` and ``--conditions innocent`` byte-equal.
    """
    import random

    random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def parse_seeds(specs: list[str]) -> list[int]:
    """Expand ``["0-49", "100"]`` -> ``[0, ..., 49, 100]``, de-duplicated, order preserved.

    Ranges are inclusive on both ends, so ``0-49`` is 50 seeds — the off-by-one that an
    exclusive reading would cause is silent in the output (49 files instead of 50).
    """
    seeds: list[int] = []
    for spec in specs:
        if "-" in spec.lstrip("-"):
            lo_s, hi_s = spec.rsplit("-", 1)
            lo, hi = int(lo_s), int(hi_s)
            if hi < lo:
                raise ValueError(f"empty seed range {spec!r} (high < low)")
            rng = range(lo, hi + 1)
        else:
            rng = [int(spec)]
        for v in rng:
            if v not in seeds:
                seeds.append(v)
    if not seeds:
        raise ValueError("--seeds expanded to nothing")
    return seeds


def decode_tag(greedy: bool, seed: Optional[int]) -> str:
    """Filename tag identifying the decode setting: ``greedy`` or ``seed<N>``.

    Greedy output does not depend on the seed, so tagging it ``seed0`` would imply a
    reproducibility knob that is not in play and would collide with a sampled run at
    seed 0.
    """
    return "greedy" if greedy else f"seed{seed}"


def _lora_layers(lora_root):
    """Every LoRA-injected layer in the model."""
    from peft.tuners.tuners_utils import BaseTunerLayer

    return [m for m in lora_root.model.modules() if isinstance(m, BaseTunerLayer)]


def assert_state(lora_root, state: str) -> None:
    """Fail loudly unless EVERY LoRA layer is in ``state`` ("em" or "base").

    The bug this guards against is silent: a half-toggled or stale adapter state still
    generates fluent text, just from the wrong model.  Checking ``_disable_adapters`` on
    every layer (rather than trusting that the last toggle did what it said) is what turns
    that into a crash instead of a plausible-looking result.  Also asserts nothing was
    merged into the weights, since a merge would make ``_disable_adapters`` a lie.
    """
    layers = _lora_layers(lora_root)
    if not layers:
        raise RuntimeError("no LoRA layers found — adapter did not attach")
    want_disabled = state == "base"
    bad = [m for m in layers if bool(getattr(m, "_disable_adapters", False)) != want_disabled]
    if bad:
        raise RuntimeError(
            f"{len(bad)}/{len(layers)} LoRA layers are not in state {state!r}"
        )
    merged = [m for m in layers if getattr(m, "merged_adapters", None)]
    if merged:
        raise RuntimeError(
            f"{len(merged)}/{len(layers)} LoRA layers have weights merged in; this script "
            "relies on enable/disable and never merges (see module docstring)"
        )


@contextlib.contextmanager
def weights(lora_root, state: str):
    """Put the model in ``state`` ("em" or "base") for the block, then restore.

    Absolute, not relative: it sets the state it wants and verifies it, so a caller never
    has to reason about what the previous block left behind.
    """
    if state not in ("em", "base"):
        raise ValueError(f"state must be 'em' or 'base', got {state!r}")
    was_disabled = bool(getattr(_lora_layers(lora_root)[0], "_disable_adapters", False))
    prev = "base" if was_disabled else "em"

    def _set(target: str) -> None:
        if target == "em":
            lora_root.enable_adapter_layers()
        else:
            lora_root.disable_adapter_layers()
        assert_state(lora_root, target)

    _set(state)
    try:
        yield
    finally:
        _set(prev)


def weight_fingerprint(mt, state: str, layer: int = 32) -> float:
    """Cheap scalar summary of the effective ``o_proj`` at ``layer`` in ``state``.

    Logged for both conditions so that "EM and base produced the same thing" is visible in
    the log as identical fingerprints, instead of having to be inferred from the outputs.
    """
    import baukit

    name = mt.attn_module_name_format.format(layer) + ".o_proj"
    o_proj = baukit.get_module(mt._model, name)
    with torch.no_grad():
        w = o_proj.base_layer.weight if hasattr(o_proj, "base_layer") else o_proj.weight
        total = w.detach().double().abs().sum().item()
        if state == "em":
            total += o_proj.get_delta_weight("default").detach().double().abs().sum().item()
    return total


def em_o_proj_weights(mt, layers: list[int]) -> dict[int, torch.Tensor]:
    """Effective EM ``o_proj.weight`` per layer: ``W_base + lora_delta``.

    ``get_delta_weight`` is peft's own accessor, so the LoRA scaling convention
    (``use_rslora=true`` here, i.e. ``alpha/sqrt(r)``) stays peft's problem rather than
    something reimplemented and silently wrong.  Returned float32 on CPU — one
    ``(n_embd, n_heads*head_dim)`` tensor per selected layer.
    """
    import baukit

    out: dict[int, torch.Tensor] = {}
    with torch.no_grad():
        for layer in layers:
            name = mt.attn_module_name_format.format(layer) + ".o_proj"
            o_proj = baukit.get_module(mt._model, name)
            if not hasattr(o_proj, "base_layer"):
                # o_proj is not a LoRA target -> module weight is already the EM weight.
                continue
            base = o_proj.base_layer.weight.detach().float().cpu()
            delta = o_proj.get_delta_weight("default").detach().float().cpu()
            out[layer] = base + delta
    return out


