def build_chat_prompt(mt: ModelandTokenizer, system: str, user: str) -> str:
    """Render a system+user turn and open the assistant turn, ready for generation.

    Ends at ``<|im_start|>assistant\n`` — the newline the chat template emits after the
    assistant header is KEPT.  Stripping it puts the model one token before the start of
    its own turn, so the first thing it generates is the missing newline (or, if steering
    is being injected at the last position, whatever stray punctuation the intervention
    pushes out).  That produced a leading ``:`` on ~15% of GoalScope verbalizations.

    Matches the convention of :func:`src.goals.goalscope._build_goalscope_prompt`, which
    reaches the same string via ``continue_final_message=True`` and an empty assistant
    turn.
    """
    return mt.tokenizer.apply_chat_template(
        [
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ],
        add_generation_prompt=True,
        tokenize=False,
    )


