    p.add_argument(
        "--head-set",
        default=None,
        help="Path to the selected-heads JSON. Defaults to "
        "head_sets/<base-short-name>/goal__lam20_thr0.9_band25-56.json.",
    )
    p.add_argument("--system-prompt", default=DEFAULT_SYSTEM_PROMPT)
    p.add_argument("--user-prompt", default=DEFAULT_USER_PROMPT)
    p.add_argument(
        "--goalscope-question",
        default=DEFAULT_GOALSCOPE_QUESTION,
        help="User turn of the GoalScope probe prompt.",
    )
    p.add_argument(
        "--conditions",
        nargs="+",
        default=["em", "innocent"],
        choices=["em", "innocent"],
        help="Which conditions to run.",
    )
    p.add_argument(
        "--slug",
        default="em_scope",
        help="Output filename stem; files are "
        "<slug>__<condition>__seed<seed>.html (or __greedy with --greedy).",
    )
    p.add_argument(
        "--greedy",
        action="store_true",
        help="Greedy-decode the response instead of sampling. Ignores --seeds and all sampling flags.",
    )
    p.add_argument(
        "--seeds",
        nargs="+",
        default=["0"],
        metavar="SPEC",
        help="RNG seeds for the sampled response; each appears in its output filename. "
        "Accepts individual values and inclusive ranges, e.g. --seeds 0-49 or "
        "--seeds 0 7 100-104. Ignored under --greedy. The model is loaded once and "
        "reused across every seed.",
    )
    # Defaults below mirror Qwen2.5-32B-Instruct's generation_config.json.  They are
    # hard-coded rather than inherited because nnsight's generate() does not pick that
