def load_pairs(task: str) -> list[tuple[str, str]]:
    kind = TASKS[task][2]
    if kind != "built":
        return [(d["input"], d["output"]) for d in json.load(open(FV / kind / f"{task}.json"))]
    if task == "antonym-spanish":       # antonym (Todd et al.), then English->Spanish (Todd et al.'s dictionary)
        ant = {d["input"]: d["output"] for d in json.load(open(FV / "abstractive/antonym.json"))}
        es = {d["input"]: d["output"] for d in json.load(open(FV / "abstractive/english-spanish.json"))}
        return [(w, es[a]) for w, a in ant.items() if a in es and " " not in a and " " not in es[a]]
    if task == "plus-ten-times-two":
        return [(str(x), str((x + 10) * 2)) for x in range(1000)]
    if task == "country-superposition":
        cap = {d["input"]: d["output"] for d in json.load(open(FV / "abstractive/country-capital.json"))}
        return [(c, k) for c in CONTINENT if c in cap for k in ("capital", "continent", "upper")]
    raise KeyError(task)


def build_prompt(task: str, rng: random.Random) -> tuple[str, list[tuple[str, str]]]:
    pairs = load_pairs(task)
    if task == "country-superposition":   # each demo follows one of the three rules at random
        cap = {d["input"]: d["output"] for d in json.load(open(FV / "abstractive/country-capital.json"))}
        countries = rng.sample(sorted({c for c, _ in pairs}), N_SHOTS + 1)
        rule = lambda c: rng.choice([cap[c], CONTINENT[c], c.upper()])
        demos = [(c, rule(c)) for c in countries[:N_SHOTS]] + [(countries[-1], "")]
    else:
        pick = rng.sample(pairs, N_SHOTS + 1)
        demos = pick[:N_SHOTS] + [(pick[-1][0], "")]
    text = "\n".join(f"Q: {q}\nA: {a}" for q, a in demos[:-1]) + f"\nQ: {demos[-1][0]}\nA:"
    return text, demos


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tasks", nargs="+", default=list(TASKS))
    ap.add_argument("--out-dir", default="results/icl_goalscope")
    ap.add_argument("--batch", type=int, default=16)
    args = ap.parse_args()
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    mt = ModelandTokenizer(model_key=MODEL, dtype=torch.bfloat16, device_map={"": 0}, attn_implementation="eager")
    tok = mt.tokenizer
    heads = [tuple(h) for h in json.load(open(HEADS))]

    def probe_prompt(setting):
        return tok.apply_chat_template([{"role": "system", "content": PROBE_SYS}, {"role": "user", "content": PROBE[setting]},
                                        {"role": "assistant", "content": ""}], tokenize=False,
                                       add_generation_prompt=False, continue_final_message=True)

    def scope(ids, positions, setting):
        inp = TokenizerOutput(data=dict(input_ids=torch.tensor([ids]), attention_mask=torch.ones(1, len(ids), dtype=torch.long)))
        rows = apply_goalscope(inp, mt=mt, selected_heads=heads, strategy="additive_norm", alpha=0.1,
                               steer_layer_range=(35, 46), batch_size=args.batch, max_new_tokens=READ_TOKENS,
                               n_steer_tokens="all", goalscope_prompt=probe_prompt(setting),
                               token_positions=positions)
        by = {int(r["pos"]): (r.get("patched_gen") or "").strip() for r in rows}
        return [by[p] for p in positions]

    def generate(text):
        inp = prepare_input(prompts=text, tokenizer=mt)
        with torch.no_grad():
            g = mt._model.generate(input_ids=inp["input_ids"], attention_mask=inp["attention_mask"],
                                   max_new_tokens=N_GEN, do_sample=False)[0].tolist()
        return g, inp["input_ids"].shape[1]

    for task in args.tasks:
        t0 = time.time()
        setting, rules, _ = TASKS[task]
        rng = random.Random(0)
        evals = []
        for k in range(N_PROMPTS):
            text, demos = build_prompt(task, rng)
            ids, n = generate(text)
            toks = [tok.decode([i]) for i in ids]
            if setting == "single":   # the "A" of the final three demonstrations
                a_pos = [i for i in range(n - 1) if toks[i] == "A" and toks[i + 1] == ":"]
                pos = a_pos[-4:-1]
            else:                     # the last prompt token + the first N_GEN generated tokens
                pos = list(range(n - 1, len(ids)))
            ev = dict(k=k, text=text, demos=demos, ids=ids, n_prompt=n, tokens=toks, positions=pos,
                      generation=tok.decode(ids[n:]), readouts=scope(ids, pos, setting))
            evals.append(ev)
            json.dump(dict(task=task, setting=setting, rules=rules, probe=PROBE[setting], probe_system=PROBE_SYS,
                           settings=dict(model=MODEL, heads=HEADS, n_heads=len(heads), strategy="additive_norm",
                                         alpha=0.1, layers=[35, 45], n_shots=N_SHOTS, n_gen=N_GEN,
                                         readout_tokens=READ_TOKENS), prompts=evals),
                      open(out_dir / f"{task}.json", "w"), ensure_ascii=False, indent=1)
        print(f"{task}: {N_PROMPTS} prompts ({time.time() - t0:.0f}s)", flush=True)
    print("done")


if __name__ == "__main__":
    main()
